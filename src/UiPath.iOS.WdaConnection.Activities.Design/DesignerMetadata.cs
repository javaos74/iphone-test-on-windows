namespace UiPath.iOS.WdaConnection.Activities.Design;

/// <summary>
/// Designer metadata registration for UiPath iOS WDA Connection Activities.
/// In .NET 6, activity designers are typically registered through attributes
/// on the activity classes themselves rather than through IRegisterMetadata.
/// </summary>
/// <remarks>
/// This class serves as a placeholder for future designer customizations.
/// Activity metadata (DisplayName, Description, Category) are defined using
/// attributes directly on the activity classes in the main Activities project.
/// </remarks>
public static class DesignerMetadata
{
    /// <summary>
    /// Gets the assembly name for the activities.
    /// </summary>
    public static string ActivitiesAssemblyName => "UiPath.iOS.WdaConnection.Activities";
    
    /// <summary>
    /// Gets the default category for activities in this package.
    /// </summary>
    public static string DefaultCategory => "iOS WDA Connection";
}
